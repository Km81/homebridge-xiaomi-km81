'use strict';

/**
 * putAway — 「임시 연결해제」 선언 (화면 문구 v2.3.1, 2026-09-14)
 *
 * ⛔★★이것은 availability 가 아니다. 기기가 죽었다는 **판정**이 아니라,
 *   사람이 "지금 이 기기는 집에 없다"고 한 **선언**이다. 그 선을 넘지 말 것.
 *   (기기별 availability 는 회귀로 금지돼 있다 — 「전원 끔」과 「사망」이 섞이고
 *    예외가 다음 사고 자리가 된다.)
 *
 * 왜 필요한가: 선풍기를 창고에 넣으면 로컬이 죽는 것이 **정상**인데, NAS 감시기는
 *   그것을 사망과 구분할 방법이 없어 6시간마다 운다.
 *   ★감시기 쪽에 무시 목록을 두면 「전량 검사」라는 성질이 깨지고 **목록 자체가 사각**이 된다
 *   (목록에 넣어 둔 것을 잊으면 진짜 고장도 조용히 넘어간다).
 *   ⇒ 원천에서 통신을 멈춰 **애초에 그 로그가 나오지 않게** 한다.
 *
 * 무엇을 멈추나: 폴링·재연결·로컬 재탐색·클라우드 조회 — 통신 전부.
 * ⛔무엇을 멈추지 않나: **액세서리 등록**. 지우면 홈 앱의 방 배치·장면이 깨진다
 *   (브릿지 재페어링 금지와 같은 부류). 타일은 남고 상태만 기본값으로 보인다.
 *
 * ⚠️설정은 기동 시 1회만 읽힌다 → 토글을 바꾸면 홈브릿지 재시작이 필요하다.
 *   ★그 덕에 "다시 켤 때 상태를 모른 채 시작한다"는 걱정은 생기지 않는다(늘 새로 시작한다).
 */

/**
 * ★기기별 옵션이므로 **devices[] 하위에서만** 읽는다.
 *   (최상위에서 읽어 기능이 통째로 꺼져 있던 전례가 있다 — fallbackToCloud.)
 * ⚠️문자열 'true' 는 받지 않는다 — 설정 UI 의 체크박스는 불리언을 넣는다.
 *   조용히 켜지는 것보다 조용히 꺼지는 편이 안전하다(감시가 계속 도는 쪽).
 */
function isPutAway(cfg) {
  return !!(cfg && cfg.putAway === true);
}

/**
 * 임시 연결해제한 기기가 기동 시 남기는 **단 한 줄**.
 *
 * ⛔★★이 문구에는 NAS 감시기(hb_watch)가 읽는 어휘가 **하나도** 들어가면 안 된다.
 *   (폴링 실패 / 상태 조회 실패 / 연결 실패 / 기기 오프라인 / 로컬 재탐색 N회 실패 /
 *    사실상 클라우드로 동작 중 / 제어되지 않습니다 / 연결됨 / 로컬 복귀 / 폴링 복구 …)
 *   들어가면 **감시에서 빼려고 만든 기능이 감시를 깨우는** 일이 된다.
 * ⚠️★단답형이다(Km81 님 지시, v2.3.2). 서술형으로 되돌리지 말 것 —
 *   「재시작해야 적용된다」 같은 설명은 README·HANDOFF §12 에만 둔다.
 * ⚠️문구를 고칠 때는 test/put_away.js 의 금지 어휘 목록을 반드시 함께 볼 것
 *   (★주석으로 적은 규칙은 안 지켜진다 — 그래서 회귀로 박아 두었다).
 */
const PUT_AWAY_MESSAGE =
  '임시 연결해제 — 통신 안 함';


/**
 * ★「임시 연결해제」 기기의 홈킷 타일을 **마지막 상태로 정상 표시**시킨다.
 *
 * Km81 님 지시(2026-09-14): *「난 정상연결로 최종 상태를 가져왔으면 해」*.
 * 그 전에는 기기마다 달랐다 — 선풍기는 「정상 연결 + 기본값」, 에어컨은 **「응답 없음」**.
 *
 * 왜 이 방법인가 — hap-nodejs 2.2.2 로 실행해 확인한 것:
 *   ① 게터(`onGet`)를 **등록하지 않으면** HAP 은 그 특성의 **현재 값으로 답한다.**
 *      그 값은 홈브릿지가 `cachedAccessories` 에서 **복원한 마지막 상태**다
 *      (실측: 거실 에어컨의 `Active=0 · 현재온도 26 · 냉방설정 24` 가 디스크에 있었다).
 *      ⇒ ★**우리가 상태를 따로 저장할 필요가 없다.**
 *   ② 게터가 한 번이라도 던지면 특성에 `status` 가 **눌러붙어 그 뒤로 계속 거부**된다.
 *      그것이 에어컨의 「응답 없음」이었다. ⛔`ch.status = null` **대입으로는 안 지워진다** —
 *      **`updateValue(ch.value)` 로만** 지워진다(실측).
 *   ③ `onSet` 이 없으면 쓰기는 **지역 값만 바꾸고 통과**한다(통신 0 · 오류 0).
 *      던지지 않으니 ②의 눌러붙음도 안 생긴다. ⇒ 그래서 게터만 떼면 안 되고 **둘 다** 뗀다.
 *
 * ⛔서비스·특성을 지우지 않는다 — 홈킷 방 배치·장면이 사라진다.
 * ⚠️체크를 풀고 재시작하면 게터가 정상 등록되므로 되돌릴 것이 없다.
 * ⚠️이 함수는 **서비스를 다 만든 뒤에** 불러야 한다 — 먼저 부르면 뗄 것이 없다(회귀가 검사한다).
 */
function sealForPutAway(accessory) {
  if (!accessory || !Array.isArray(accessory.services)) return 0;
  let n = 0;
  for (const svc of accessory.services) {
    const chars = (svc && svc.characteristics) || [];
    for (const ch of chars) {
      try {
        if (typeof ch.removeOnGet === 'function') ch.removeOnGet();
        if (typeof ch.removeOnSet === 'function') ch.removeOnSet();
        // ★눌러붙은 status 를 지운다. 값이 없는 특성은 건드리지 않는다(경고가 난다).
        if (ch.value !== null && ch.value !== undefined && typeof ch.updateValue === 'function') {
          ch.updateValue(ch.value);
        }
        n += 1;
      } catch (e) { /* 한 특성이 실패해도 나머지는 계속 — 표시 문제로 기동을 막지 않는다 */ }
    }
  }
  return n;
}

module.exports = { isPutAway, PUT_AWAY_MESSAGE, sealForPutAway };
